            for year in years:
                ydf = dm[dm[yc] == year]
                if len(ydf) == 0:
                    continue
                fg = folium.FeatureGroup(name=f"{year} Violations{sn}")
                mc = MarkerCluster().add_to(fg)
                for _, row in ydf.iterrows():
                    popup = f"<b>Year:</b> {row.get(yc,'N/A')}<br>"
