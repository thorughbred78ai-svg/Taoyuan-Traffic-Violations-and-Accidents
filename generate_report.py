def compute_yoy_change(series):
    """Compute year-over-year change rate from a sorted series"""
    if series is None or len(series) < 2:
        return None, None
    values = series.values
    years = series.index
    latest = values[-1]
    prev = values[-2]
    if prev == 0:
        return None, latest
    change = (latest - prev) / prev * 100
    return change, latest


